CREATE TABLE IF NOT EXISTS jingo_weather_cache (
 id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 data JSON NULL,
 fetched_at BIGINT NOT NULL DEFAULT 0,
 next_attempt BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jingo_weather_usage (
 month VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 calls INT NOT NULL DEFAULT 0,
 blocked BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;
