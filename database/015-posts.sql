CREATE TABLE IF NOT EXISTS jingo_post_categories (
 name VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin PRIMARY KEY,
 english_name VARCHAR(100) NULL,
 version INT NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jingo_posts (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 slug VARCHAR(160) CHARACTER SET ascii NOT NULL UNIQUE,
 data JSON NOT NULL,
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jingo_post_revisions (
 post_id CHAR(36) CHARACTER SET ascii NOT NULL,
 version INT NOT NULL,
 data JSON NOT NULL,
 saved_by VARCHAR(80) NOT NULL,
 reason VARCHAR(80) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(post_id,version),
 FOREIGN KEY(post_id) REFERENCES jingo_posts(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jingo_post_metrics (
 post_id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 views BIGINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(post_id) REFERENCES jingo_posts(id)
) ENGINE=InnoDB;
