CREATE TABLE IF NOT EXISTS jingo_ride_pools (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 visit_date CHAR(10) CHARACTER SET ascii NOT NULL,
 from_id VARCHAR(80) COLLATE utf8mb4_bin NOT NULL,
 to_id VARCHAR(80) COLLATE utf8mb4_bin NOT NULL,
 vehicle_id VARCHAR(80) COLLATE utf8mb4_bin NOT NULL,
 departure CHAR(5) CHARACTER SET ascii NOT NULL,
 target INT NOT NULL,
 total BIGINT NOT NULL,
 status VARCHAR(20) CHARACTER SET ascii NOT NULL DEFAULT 'OPEN',
 data JSON NOT NULL,
 version INT NOT NULL DEFAULT 1,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX ride_pool_day(visit_date,vehicle_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
