CREATE TABLE IF NOT EXISTS jingo_orders (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY,
 code CHAR(12) CHARACTER SET ascii NOT NULL UNIQUE,
 request_id CHAR(36) CHARACTER SET ascii NOT NULL UNIQUE,
 request_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 access_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 snapshot JSON NOT NULL,
 contact JSON NOT NULL,
 booking_status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
 payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID',
 instructions TEXT NOT NULL,
 version INT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jingo_order_limits (
 id CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 attempts INT NOT NULL,
 until_at DATETIME NOT NULL,
 INDEX(until_at)
) ENGINE=InnoDB;
